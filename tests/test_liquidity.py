import unittest
from unittest.mock import patch
import numpy as np
import pandas as pd
from AgentBasedModel.agents.agents import ExchangeAgent, Chartist, MarketMaker
from AgentBasedModel.utils.orders import Order, OrderList, EmptyOrderBookError
from AgentBasedModel.utils.liquidity import empty_spells, liquidity_summary
from experiments import liquidity_aware_recovery_time, compute_recovery_time_relative, aggregate_results
from recovery_reporting import observation_fields


def market():
    m=ExchangeAgent(volume=0)
    m.order_book['bid'].append(Order(99,5,'bid'))
    m.order_book['ask'].append(Order(101,2,'ask'))
    return m


class LiquidityTests(unittest.TestCase):
    def test_last_midpoint_survives_depletion_and_updates_after_recovery(self):
        m=market();buyer=Chartist(m,1000,0)
        m.market_order(Order(101,2,'bid',buyer))
        self.assertEqual(m.price(),100)
        self.assertEqual((buyer.cash,buyer.assets),(798,2))
        for _ in range(3):self.assertEqual(m.price(),100)
        self.assertEqual((buyer.cash,buyer.assets),(798,2))
        m.order_book['ask'].append(Order(105,3,'ask'))
        self.assertEqual(m.price(),102)
        m.cancel_order(m.order_book['ask'].first)
        self.assertEqual(m.price(),102)

    def test_no_history_fails_but_both_empty_preserves_observed_midpoint(self):
        m=ExchangeAgent(volume=0)
        with self.assertRaises(EmptyOrderBookError):m.price()
        m.order_book['bid'].append(Order(99,1,'bid'))
        with self.assertRaises(EmptyOrderBookError):m.price()
        m.order_book['ask'].append(Order(101,1,'ask'));m.price()
        m.order_book={'bid':OrderList('bid'),'ask':OrderList('ask')}
        self.assertEqual(m.price(),100.)

    def test_chartist_missing_quote_does_not_draw_limit_price_or_make_orders(self):
        m=market();m.price();m.order_book['ask']=OrderList('ask')
        t=Chartist(m,1000,0)
        for sentiment in ['Optimistic','Pessimistic']:
            t.sentiment=sentiment
            with patch('random.random',return_value=.7),patch.object(t,'_buy_limit') as buy,patch.object(t,'_sell_limit') as sell:
                t.call();buy.assert_not_called();sell.assert_not_called()
        self.assertEqual((t.cash,t.assets,t.orders),(1000,0,[]))
        t._sell_limit(1,101)
        self.assertFalse(t.orders)

    def test_market_maker_does_not_refill_one_sided_book(self):
        m=market();m.price();m.order_book['ask']=OrderList('ask');t=MarketMaker(m,1000)
        t.call();self.assertFalse(t.orders);self.assertFalse(m.order_book['ask'])
        self.assertEqual((t.cash,t.assets),(1000,0))

    def test_empty_both_no_fictitious_execution_and_real_quotes_restore_price(self):
        from AgentBasedModel.utils.liquidity import quote_state
        m=market();m.price();t=Chartist(m,1000,2)
        m.order_book={'bid':OrderList('bid'),'ask':OrderList('ask')}
        self.assertEqual(quote_state(m)['state'],'empty_both')
        for side in ['bid','ask']:
            order=Order(100,3,side,t)
            self.assertEqual(m.market_order(order).qty,3)
        self.assertEqual((t.cash,t.assets),(1000,2))
        with patch('random.random',return_value=.9):t.call()
        self.assertEqual((t.cash,t.assets),(1000,2))
        self.assertFalse(m.order_book['bid']);self.assertFalse(m.order_book['ask'])
        self.assertEqual(m.price(),100)
        # Explicit real test orders, not generated by the fallback implementation.
        m.order_book['bid'].append(Order(103,1,'bid'))
        self.assertEqual(m.price(),100)
        m.order_book['ask'].append(Order(105,1,'ask'))
        self.assertEqual(m.price(),104)
        self.assertEqual(quote_state(m)['state'],'two_sided')
        self.assertEqual((t.cash,t.assets),(1000,2))

    def test_state_counts_and_recoveries_are_disjoint(self):
        from AgentBasedModel.utils.liquidity import quote_history_summary
        result=quote_history_summary([False,True,True,False,False],
                                     [False,False,True,False,True])
        self.assertEqual(result['two_sided_steps'],2)
        self.assertEqual(result['one_sided_steps'],2)
        self.assertEqual(result['empty_both_steps'],1)
        self.assertEqual(result['two_sided_recoveries'],1)
        self.assertEqual(result['fallback_observation_fraction'],.6)
        self.assertEqual(result['longest_empty_period'],2)

    def test_liquidity_recovery_waits_for_both_markets(self):
        gap=[1.,1.,1.,.9,.8,.7];a=[True]*6;b=[True,True,False,False,True,True]
        self.assertEqual(compute_recovery_time_relative(gap,2),0)
        self.assertEqual(liquidity_aware_recovery_time(gap,a,b,2),2)
        self.assertTrue(np.isnan(liquidity_aware_recovery_time(gap,a,[False]*6,2)))
        self.assertTrue(np.isnan(liquidity_aware_recovery_time(gap,[],[],2)))

    def test_sampled_spells_and_right_censoring(self):
        flags=[False,True,True,False,True]
        self.assertEqual(empty_spells(flags),[dict(start=1,duration=2,right_censored=False),dict(start=4,duration=1,right_censored=True)])
        self.assertEqual(liquidity_summary(flags)['empty_steps'],3)
        self.assertEqual(liquidity_summary(flags)['longest_empty_period'],2)

    def test_recovery_metrics_have_separate_censoring(self):
        rows=[]
        for seed,value in [(1,0.),(2,np.nan)]:
            row=dict(seed=seed,run_id=seed,tau=0,beta=0,fx_cost=0,shock_iteration=2,recovery_time=0.,liquidity_recovery_time=value,recovery_b=0.,liquidity_recovery_available=True)
            row.update(observation_fields(row,status='completed',requested=6,completed=6));rows.append(row)
        # Test bookkeeping directly; aggregate_results also requires the financial metrics.
        from recovery_reporting import recovery_summary
        s=recovery_summary(pd.DataFrame(rows),['tau','beta','fx_cost']).iloc[0]
        self.assertEqual(s.recovery_time_fraction_completed_valid,1.)
        self.assertEqual(s.liquidity_recovery_time_fraction_completed_valid,.5)
        self.assertEqual(s.liquidity_recovery_time_censored_fraction_completed_valid,.5)
        self.assertEqual(s.recovery_time_censored_fraction_completed_valid,0.)

if __name__=='__main__':unittest.main()
